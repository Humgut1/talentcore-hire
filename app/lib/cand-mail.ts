/* =========================================================
   Cadence — 후보자에게 보내는 메일 '문안' (순수 함수)
   ---------------------------------------------------------
   무엇을 말할지만 여기서 정한다. 어떻게 보내는지는 mailer.ts,
   보낸 기록은 maillog.ts. 세 가지를 섞지 않는다(iv-mail.ts 와 같은 규칙).

   AI 는 쓰지 않는다 — 확정된 방침이다. 대신 상황별 템플릿을 주고,
   사람이 보내기 전에 고칠 수 있게 한다. 채용 메일은 회사 이름으로
   나가는 글이라, 사람이 읽고 손댄 문장만 나가는 편이 낫다.
   ========================================================= */

export interface MailCtx {
  cand: string          // 후보자 이름
  pos: string           // 공고 이름
  stage: string         // 지금 단계 이름
  rc: string            // 담당 리크루터 이름
  company?: string
  when?: string         // 확정된 면접 시각(있으면)
  dur?: number
  mode?: string
}

export interface MailTpl {
  v: string             // 종류 코드 — 기록에 남는다
  l: string             // 목록에 보이는 이름
  d: string             // 언제 쓰는지 한 줄
  make: (c: MailCtx) => { subject: string; body: string }
}

